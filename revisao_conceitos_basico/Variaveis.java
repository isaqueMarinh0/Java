package revisao_conceitos_basico;

public class Variaveis {
	public static void main(String[] args) {
		//Declaração de variáveis
		int x = 10; 
		String nome = "Isaque Marinho";
		System.out.println(nome);
		System.out.println(x);
		
		//Declarando variáveis constantes (que não vão mudar)
		final int y = 20; //Não é possível mudar o valor dessa variável
		// y = 10 vai retornar um erro
		
	}
}
